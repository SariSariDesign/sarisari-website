import type { Metadata } from "next";
import dynamic from "next/dynamic";
import { Instrument_Serif, Instrument_Sans, Space_Grotesk } from "next/font/google";
import { AnnotateGate } from "@/components/dev/AnnotateGate";
import { openGraphBase } from "@/lib/metadata";
import "./globals.css";

/**
 * Dev-only visual tooling (Agentation feedback toolbar + DialKit control panel).
 * The dynamic import lives inside a statically-false branch in production
 * (NODE_ENV is inlined at build time), so `agentation`, `dialkit`, and `motion`
 * are tree-shaken out of the production bundle and never ship.
 */
const DevTools =
  process.env.NODE_ENV === "development"
    ? dynamic(() => import("@/components/dev/DevTools").then((m) => m.DevTools))
    : null;

// The comp's typefaces — the free analogs of the studio's paid faces. These render as
// the live fallback (via CSS-var font stacks in globals.css) until PP Editorial Old /
// Neue Montreal / Supply are licensed into /public/fonts.
const instrumentSerif = Instrument_Serif({
  subsets: ["latin"],
  weight: "400",
  style: ["normal", "italic"],
  variable: "--font-instrument-serif",
  display: "swap",
});
const instrumentSans = Instrument_Sans({
  subsets: ["latin"],
  variable: "--font-instrument-sans",
  display: "swap",
});
const spaceGrotesk = Space_Grotesk({
  subsets: ["latin"],
  variable: "--font-space-grotesk",
  display: "swap",
});

/** Google Tag Manager container. Loaded first in <head> on every page (root layout). */
const GTM_ID = "GTM-WGXK2MTZ";
const gtmSnippet = `(function(w,d,s,l,i){w[l]=w[l]||[];w[l].push({'gtm.start':
new Date().getTime(),event:'gtm.js'});var f=d.getElementsByTagName(s)[0],
j=d.createElement(s),dl=l!='dataLayer'?'&l='+l:'';j.async=true;j.src=
'https://www.googletagmanager.com/gtm.js?id='+i+dl;f.parentNode.insertBefore(j,f);
})(window,document,'script','dataLayer','${GTM_ID}');`;

// Mirrors the homepage hero (hero.headline / eyebrow / subhead in content/site.ts).
const title = "Sari Sari | Design that turns users into regulars";
const description =
  "A senior-led design and development studio helping Seed to Series A founders launch, fix and grow products people trust.";

export const metadata: Metadata = {
  title: { default: title, template: "%s — Sari Sari Design" },
  description,
  metadataBase: new URL("https://www.sarisari.design"),
  // Link-preview (unfurl) card. The image is generated by app/opengraph-image.tsx,
  // which Next wires into both Open Graph and Twitter automatically.
  openGraph: {
    ...openGraphBase,
    title,
    description,
    url: "/",
  },
  twitter: {
    card: "summary_large_image",
    title,
    description,
  },
};

export default function RootLayout({ children }: { children: React.ReactNode }) {
  return (
    <html
      lang="en"
      className={`${instrumentSerif.variable} ${instrumentSans.variable} ${spaceGrotesk.variable}`}
    >
      <head>
        {/* Google Tag Manager */}
        <script dangerouslySetInnerHTML={{ __html: gtmSnippet }} />
        {/* End Google Tag Manager */}
      </head>
      <body className="antialiased">
        {/* Google Tag Manager (noscript) */}
        <noscript>
          <iframe
            src={`https://www.googletagmanager.com/ns.html?id=${GTM_ID}`}
            height="0"
            width="0"
            style={{ display: "none", visibility: "hidden" }}
          />
        </noscript>
        {/* End Google Tag Manager (noscript) */}
        {/* Mark JS-capable before paint so scroll-reveal only hides content when it can
            actually reveal it (see the `.js [data-reveal]` rules in globals.css). */}
        <script
          dangerouslySetInnerHTML={{ __html: "document.documentElement.classList.add('js')" }}
        />
        {children}
        {/* Local dev: DevTools. Vercel previews: Agentation via AnnotateGate. Production: neither. */}
        {DevTools ? <DevTools /> : <AnnotateGate />}
      </body>
    </html>
  );
}

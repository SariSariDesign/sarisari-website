import type { Metadata } from "next";
import dynamic from "next/dynamic";
import { Instrument_Serif, Instrument_Sans, Space_Grotesk } from "next/font/google";
import { Analytics } from "@/components/Analytics";
import { AnnotateGate } from "@/components/dev/AnnotateGate";
import { openGraphBase } from "@/lib/metadata";
import "./globals.css";

/**
 * Dev-only visual tooling (Agentation feedback toolbar + DialKit control panel).
 * The dynamic import lives inside a statically-false branch in production
 * (NODE_ENV is inlined at build time), so `agentation`, `dialkit`, and `motion`
 * are tree-shaken out of the production bundle and never ship.
 */
const DevTools =
  process.env.NODE_ENV === "development"
    ? dynamic(() => import("@/components/dev/DevTools").then((m) => m.DevTools))
    : null;

// The comp's typefaces — the free analogs of the studio's paid faces. These render as
// the live fallback (via CSS-var font stacks in globals.css) until PP Editorial Old /
// Neue Montreal / Supply are licensed into /public/fonts.
const instrumentSerif = Instrument_Serif({
  subsets: ["latin"],
  weight: "400",
  style: ["normal", "italic"],
  variable: "--font-instrument-serif",
  display: "swap",
});
const instrumentSans = Instrument_Sans({
  subsets: ["latin"],
  variable: "--font-instrument-sans",
  display: "swap",
});
const spaceGrotesk = Space_Grotesk({
  subsets: ["latin"],
  variable: "--font-space-grotesk",
  display: "swap",
});

const title =
  "Sari Sari — Senior product design & development for growth-stage software companies";
const description =
  "Your fractional product team: senior product design and development in one team, aimed at the numbers that decide your next round — activation, conversion, retention, satisfaction.";

export const metadata: Metadata = {
  title: { default: title, template: "%s — Sari Sari Design" },
  description,
  metadataBase: new URL("https://www.sarisari.design"),
  // Link-preview (unfurl) card. The image is generated by app/opengraph-image.tsx,
  // which Next wires into both Open Graph and Twitter automatically.
  openGraph: {
    ...openGraphBase,
    title,
    description,
    url: "/",
  },
  twitter: {
    card: "summary_large_image",
    title,
    description,
  },
};

export default function RootLayout({ children }: { children: React.ReactNode }) {
  return (
    <html
      lang="en"
      className={`${instrumentSerif.variable} ${instrumentSans.variable} ${spaceGrotesk.variable}`}
    >
      <body className="antialiased">
        {/* Mark JS-capable before paint so scroll-reveal only hides content when it can
            actually reveal it (see the `.js [data-reveal]` rules in globals.css). */}
        <script
          dangerouslySetInnerHTML={{ __html: "document.documentElement.classList.add('js')" }}
        />
        {children}
        {/* Deployed builds get Agentation only on opt-in (Vercel previews or ?annotate). */}
        {DevTools ? <DevTools /> : <AnnotateGate />}
        <Analytics />
      </body>
    </html>
  );
}

#!/usr/bin/env node
// Copies the anchor and band sections of the canonical Activation Scoring Rubric
// (00_Vault/02_Areas/05_design/activation-scoring-rubric.md) into a generated
// module the automated generator reads. Run after every approved rubric bump:
//   node scripts/sync-rubric.mjs /path/to/activation-scoring-rubric.md
// Then update RUBRIC in src/lib/scorecard/rubric.ts if weights, bands or profiles changed.
import { readFileSync, writeFileSync } from "node:fs";

const src = process.argv[2];
if (!src) { console.error("usage: sync-rubric.mjs <rubric.md>"); process.exit(1); }
const md = readFileSync(src, "utf8");
const version = md.match(/\*\*Version:\*\*\s*([0-9.]+[A-Z-]*)/)?.[1];
if (!version) throw new Error("rubric version not found");
const section = (n) => {
  const m = md.match(new RegExp(`\\n## ${n}\\. [\\s\\S]*?(?=\\n## \\d+\\. |$)`));
  if (!m) throw new Error(`section ${n} not found`);
  return m[0].trim().replace(/\n-{3,}\s*$/, "").trim();
};
const out = `// GENERATED by scripts/sync-rubric.mjs from activation-scoring-rubric.md. Do not edit by hand.
export const RUBRIC_SOURCE_VERSION = ${JSON.stringify(version)};
export const RUBRIC_ANCHORS = ${JSON.stringify(section(4))};
`;
writeFileSync(new URL("../src/lib/scorecard/rubric-anchors.generated.ts", import.meta.url), out);
console.log(`synced rubric v${version}`);
